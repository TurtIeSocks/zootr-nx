//! The music table's tracks by name: a seed's pools are assigned by name,
//! and each track's song length and loop flag are kept here since the
//! streams aren't in the extract cache (a dump test checks every one
//! against its stream). The guard skips this file (`known/guard.rs`).

use super::Pool::{self, *};
use super::Track;

/// The music table: each track's graph, the streams its asset nodes play.
pub const TABLE: &str = "Sound/Bgm/bgm.Product.111.byml.zs";

/// Where the streams are, as `{STREAMS}NAME.bwav`.
pub const STREAMS: &str = "Sound/Resource/Stream/";

/// Keys never rewritten: the build-up a get fanfare holds while the chest
/// opens, before its own stream.
pub const HELD: [&str; 1] = ["BGM_ItemGet_Intro"];

const fn t(
    id: &'static str,
    label: &'static str,
    pool: Pool,
    graph: &'static str,
    song: Option<&'static str>,
    secs: f32,
    looping: bool,
) -> Track {
    Track {
        id,
        label,
        pool,
        graph,
        song,
        secs,
        looping,
    }
}


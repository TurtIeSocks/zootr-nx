//! A dungeon's room files, written from what derive traced over its maps.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write as _;

use crate::rules::kinds::Kind;
use crate::rules::quote;
use crate::rules::rooms::{self, Flag};
use crate::sweep::spot::slug;

use super::locks::{Lock, flag_rule};
use super::seen::{Seen, link};
use super::{Jump, NAMES};

/// A check as a room file writes it.
pub(super) struct CheckOut {
    pub hash: u64,
    /// `None` names it by its room: a gold skulltula nothing else names.
    pub name: Option<String>,
    pub needs: String,
    pub why: String,
    pub guess: bool,
}

/// What derive traced over a dungeon's maps, for its room files.
#[derive(Default)]
pub(super) struct Traced<'k> {
    /// What was seen crossing from one room to another, by (from, to, via).
    pub seen: BTreeMap<(u32, u32, rooms::Via), Seen<'k>>,
    /// Each obstacle's flags, by its placement.
    pub locks: HashMap<u64, Vec<Lock>>,
    /// Each flag by its game name, with the kinds of what sets it.
    pub flags: BTreeMap<String, (Lock, Vec<&'k Kind>)>,
    /// Each room's checks.
    pub checks: BTreeMap<u32, Vec<CheckOut>>,
    /// Each room's exits and arrival spots, by key, with their names.
    pub spots: BTreeMap<(u32, &'static str), BTreeMap<u32, String>>,
}

/// The room files of `numbered` rooms under `baseline/{folder}/`, by path,
/// and each jump link at its narrowest. `placed` holds the flags a
/// confirmed entry places, written as confirmed rather than traced.
pub(super) fn room_files(
    folder: &str,
    numbered: &BTreeSet<u32>,
    mut traced: Traced<'_>,
    placed: &HashMap<u32, (u32, &Flag)>,
) -> (Vec<(String, String)>, Vec<Jump>) {
    let names = NAMES.get(folder);
    let (mut files, mut jumps) = (vec![], vec![]);
    for &room in numbered {
        let name = names.and_then(|n| n.get(&room));
        let file = match name {
            Some(n) => format!("room-{room:02}-{}.toml", slug(n)),
            None => format!("room-{room:02}.toml"),
        };
        let words = name.cloned().unwrap_or_else(|| format!("Room {room:02}"));
        let mut out = format!(
            "# Generated by `zootr logic derive`. Don't edit: confirmed/ overrides it.\nroom = {room}\nname = {}\n",
            quote(&words)
        );
        let mut entry = |table: &str, fields: &[(&str, String)], guess: bool| {
            write!(out, "\n[[{table}]]\n").unwrap();
            for (k, v) in fields {
                writeln!(out, "{k} = {v}").unwrap();
            }
            if guess {
                out += "guess = true\n";
            }
        };
        let from_here = (room, 0, rooms::Via::Walk)..=(room, u32::MAX, rooms::Via::Event);
        for (&(_, to, via), s) in traced.seen.range(from_here) {
            if via == rooms::Via::Jump && s.puzzle.is_none() {
                let (from, width, at) = (room, s.least, s.at);
                jumps.push(Jump {
                    from,
                    to,
                    width,
                    at,
                });
            }
            let (needs, why, guess) = link(via, (room, to), s, &traced.locks);
            let fields = [
                ("to", to.to_string()),
                ("needs", quote(&needs)),
                ("via", quote(via.word())),
                ("why", quote(&why)),
            ];
            entry("link", &fields, guess);
        }
        let mut here = traced.checks.remove(&room).unwrap_or_default();
        here.sort_by_key(|c| c.hash);
        let unnamed = here.iter().filter(|c| c.name.is_none()).count();
        let mut nth = 0;
        for c in here {
            let name = c.name.unwrap_or_else(|| {
                nth += 1;
                match unnamed {
                    1 => format!("{words} Gold Skulltula"),
                    _ => format!("{words} Gold Skulltula {nth}"),
                }
            });
            let fields = [
                ("hash", c.hash.to_string()),
                ("name", quote(&name)),
                ("needs", quote(&c.needs)),
                ("why", quote(&c.why)),
            ];
            entry("check", &fields, c.guess);
        }
        let mut set_here: Vec<&(Lock, Vec<&Kind>)> = (traced.flags.values())
            .filter(|(l, _)| l.room == Some(room) && !placed.contains_key(&l.hash()))
            .collect();
        set_here.sort_by_key(|(l, _)| l.hash());
        for (lock, kinds) in set_here {
            let (needs, why, guess) = flag_rule(lock, kinds);
            let fields = [
                ("hash", format!("0x{:08x}", lock.hash())),
                ("name", quote(&crate::derive::words(&lock.name))),
                ("needs", quote(&needs)),
                ("why", quote(&why)),
            ];
            entry("flag", &fields, guess);
        }
        let mut confirmed_here: Vec<&Flag> = (placed.values())
            .filter(|(r, _)| *r == room)
            .map(|(_, f)| *f)
            .collect();
        confirmed_here.sort_by_key(|f| f.hash);
        for f in confirmed_here {
            let fields = [
                ("hash", format!("0x{:08x}", f.hash)),
                ("name", quote(&f.name)),
                ("needs", quote(&f.needs)),
                ("why", quote(&format!("confirmed: {}", f.why))),
            ];
            entry("flag", &fields, f.guess);
        }
        for table in ["exit", "arrival"] {
            for (hash, name) in traced.spots.get(&(room, table)).into_iter().flatten() {
                entry(
                    table,
                    &[("hash", format!("0x{hash:08x}")), ("name", quote(name))],
                    false,
                );
            }
        }
        files.push((format!("baseline/{folder}/{file}"), out));
    }
    (files, jumps)
}

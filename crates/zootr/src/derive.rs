//! `zootr logic derive`: writes `logic/baseline/` from the game's data,
//! which no one edits by hand (room reach spec).

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::Result;
use ounce_formats::{Romfs, murmur3};

use crate::checks::{GYAML, actors, bancs, str_field};
use crate::entrances::DUNGEONS;
use crate::rules::kinds::{FILE, Sets};
use crate::tools::Tools;
use crate::world::node_of;

pub mod rooms;

/// Only these are objects. The rest of a dungeon's actors are enemies,
/// people, scenery models and managers.
const PREFIXES: &[&str] = &["Obj_", "FldObj_"];

/// Name families that say what a kind does when its pack doesn't, first
/// match wins, and whether that's a guess a live test should settle.
const FAMILIES: &[(&str, Sets, bool)] = &[
    // A shutter opens when its placement's flag is set, which derive
    // finds per placement.
    ("SwitchShutter", Sets::Opens, false),
    ("HookShotTarget", Sets::TargetHookshot, false),
    // Its pack's AI fires on hits, and its placement's logic reads that.
    ("EyeSwitch", Sets::Flag, false),
    ("Switch", Sets::Flag, true),
    ("switch", Sets::Flag, true),
    ("CandleStick", Sets::Flag, true),
    ("CandleStand", Sets::Flag, true),
    ("RupeeToken", Sets::Flag, true),
    ("EnemyCounter", Sets::Flag, true),
    ("MoveFloor", Sets::Platform, true),
    ("RiseFloor", Sets::Platform, true),
    ("SinkFloor", Sets::Platform, true),
    ("FloatFloor", Sets::Platform, true),
    ("HangingFloor", Sets::Platform, true),
    ("ElevatedFloor", Sets::Platform, true),
    ("PivotedFloor", Sets::Platform, true),
    ("RotateFloor", Sets::Platform, true),
    ("SwayingFloor", Sets::Platform, true),
    ("GimmickFloor", Sets::Platform, true),
    ("Elevator", Sets::Platform, true),
    ("ExtendingPlatform", Sets::Platform, true),
    ("PaddleShip", Sets::Platform, true),
    ("MoveClimbWall", Sets::Platform, true),
    ("SpiralStaircase", Sets::Platform, true),
    ("WaterPlaneDynamic", Sets::Platform, true),
];

/// Every object kind placed in a dungeon, its boss room included.
fn dungeon_kinds(romfs: &Romfs) -> Result<BTreeSet<String>> {
    let in_dungeon = |node: &str| {
        DUNGEONS.iter().any(|d| {
            node.starts_with(d.node.get()) || d.boss.is_some_and(|b| node.starts_with(b.get()))
        })
    };
    let mut kinds = BTreeSet::new();
    for (file, doc) in bancs(romfs)? {
        if !in_dungeon(&node_of(&file).0) {
            continue;
        }
        for actor in actors(&doc?.root)? {
            let gyaml = str_field(actor, GYAML).unwrap_or_default();
            if PREFIXES.iter().any(|p| gyaml.starts_with(p)) {
                kinds.insert(gyaml.to_owned());
            }
        }
    }
    Ok(kinds)
}

/// An actor's name in words: its parts and their capitals split apart.
pub(crate) fn words(gyaml: &str) -> String {
    let rest = PREFIXES
        .iter()
        .find_map(|p| gyaml.strip_prefix(p))
        .unwrap_or(gyaml);
    let mut out = String::new();
    for part in rest.split('_').filter(|p| !p.is_empty()) {
        let mut prev_lower = false;
        for (i, c) in part.chars().enumerate() {
            if (i == 0 && !out.is_empty()) || (c.is_ascii_uppercase() && prev_lower) {
                out.push(' ');
            }
            out.push(if i == 0 { c.to_ascii_uppercase() } else { c });
            prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        }
    }
    out
}

/// `baseline/kinds.toml`, from the tool table's readers.
pub fn kinds_text(romfs: &Romfs) -> Result<String> {
    let mut tools = Tools::new(romfs);
    let mut rows = Vec::new();
    for gyaml in dungeon_kinds(romfs)? {
        let said = tools.explain(&gyaml)?;
        let family = FAMILIES.iter().find(|(f, ..)| gyaml.contains(f));
        let (uses, mut why, mut guess) = match said {
            Some((rule, why, guess)) => (rule.unwrap_or_else(|| "always".into()), why, guess),
            None => ("always".into(), "no obstacle".into(), false),
        };
        let sets = match family {
            Some((frag, sets, family_guess)) => {
                write!(why, "; name `{frag}`: {}", sets.word())?;
                guess |= family_guess;
                *sets
            }
            None if uses != "always" => Sets::Opens,
            None => Sets::None,
        };
        rows.push((
            words(&gyaml),
            murmur3(gyaml.as_bytes()),
            uses,
            sets,
            why,
            guess,
        ));
    }
    rows.sort_by_key(|r| (r.0.clone(), r.1));
    let mut out = format!(
        "# Generated by `zootr logic derive --kinds`. Don't edit:\n\
         # confirmed/{FILE} overrides it. guess = true marks a kind only a\n\
         # live test settles.\n"
    );
    for (name, hash, uses, sets, why, guess) in rows {
        let q = |s: &str| toml::Value::String(s.to_owned()).to_string();
        write!(
            out,
            "\n[[kind]]\nhash = 0x{hash:08x}\nname = {}\nuses = {}\nsets = {}\nwhy = {}\n",
            q(&name),
            q(&uses),
            q(sets.word()),
            q(&why)
        )?;
        if guess {
            out += "guess = true\n";
        }
    }
    Ok(out)
}

/// Writes `baseline/kinds.toml` under the logic folder `dir`, returning
/// how many kinds and how many guesses.
pub fn kinds(romfs: &Romfs, dir: &Path) -> Result<(usize, usize)> {
    let text = kinds_text(romfs)?;
    let path = dir.join("baseline").join(FILE);
    std::fs::create_dir_all(path.parent().unwrap())?;
    std::fs::write(&path, &text)?;
    let count = |needle: &str| text.matches(needle).count();
    Ok((count("[[kind]]"), count("guess = true")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_name_in_words() {
        assert_eq!(
            words("Obj_FakeTemple_SpiderWeb_A_02"),
            "Fake Temple Spider Web A 02"
        );
        assert_eq!(words("FldObj_fakeRupeeCounter_03"), "Fake Rupee Counter 03");
    }

    /// The committed baseline matches a fresh derive, like the AP export.
    #[test]
    fn the_committed_kinds_match_a_fresh_derive() {
        let Some(romfs) = crate::game::dev_dump() else {
            return;
        };
        let committed = include_str!("../logic/baseline/kinds.toml");
        assert!(
            kinds_text(&romfs).unwrap() == committed,
            "baseline/kinds.toml is stale: run `zootr logic derive --kinds`"
        );
    }
}
